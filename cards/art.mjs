async function generate(id, subject) {
  const res = await fetch(
    "https://ai.api.cloud.yandex.net/v1/images/generations",
    {
      method: "POST",
      headers: {
        Authorization: `Api-Key ${KEY}`,
        "OpenAI-Project": FOLDER,
        "Content-Type": "application/json",
      },
      body: JSON.stringify({
        model: `art://${FOLDER}/yandex-art-2.0/latest`,
        prompt: `${subject}, ${STYLE}`,
        response_format: "b64_json",
        size: "1024x1024",
      }),
      signal: AbortSignal.timeout(180_000),
    },
  );

  const data = await res.json();
  const b64 = data?.data?.[0]?.b64_json;

  if (!b64) {
    console.log(`${id}: не вышло — ${JSON.stringify(data).slice(0, 160)}`);
    return false;
  }

  // Отдаёт JPEG независимо от того, как назвать файл.
  writeFileSync(`${OUT}${id}.jpg`, Buffer.from(b64, "base64"));
  console.log(`${id}.jpg`);
  return true;
}

mkdirSync(OUT, { recursive: true });

const only = process.argv[2];
const ids = only ? [only] : Object.keys(PROMPTS);
let made = 0;

for (const id of ids) {
  const subject = PROMPTS[id];
  if (!subject) {
    console.log(`нет такого ключа: ${id}`);
    continue;
  }

  // Готовое не перерисовываем без прямой просьбы: каждая попытка платная,
  // а результат всё равно выйдет другим.
  if (!only && existsSync(`${OUT}${id}.jpg`)) continue;

  if (await generate(id, subject)) made++;
}

console.log(`\nготово: ${made} фонов в cards/bg/`);
