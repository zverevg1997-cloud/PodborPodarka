// Фоны для карточек: YandexART 2.0.
//
// Отделено от отрисовки нарочно. Генерация стоит денег и идёт минуту на
// картинку, а собрать карточку поверх готового фона можно сколько угодно
// раз бесплатно. Поэтому сначала гоняем это, потом cards/make.mjs.
//
// Запуск: node cards/art.mjs [ключ]
//   без ключа — только те фоны, которых ещё нет
//   с ключом  — перерисовать один, если не понравился
//
// Что выяснилось на пробах:
//   · просьбу «плоская векторная графика» модель игнорирует и всё равно
//     рисует фотографию, так что не спорим и просим фотографию сразу;
//   · отрицания читаются наоборот. На «без новогоднего декора» она нарисовала
//     ёлку с игрушками и снег за окном — слово из запрета попадает в сюжет.
//     Поэтому запретов здесь нет вовсе: вместо них сказано, что должно быть,
//     то есть ранняя осень и чистые поверхности;
//   · надписи всё равно выходят кашей, поэтому всё, что нужно прочесть,
//     накладывается поверх в cards/make.mjs.

import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";

const ROOT = new URL("../", import.meta.url).pathname.slice(1);
const OUT = new URL("bg/", import.meta.url).pathname.slice(1);

const env = Object.fromEntries(
  readFileSync(`${ROOT}.env`, "utf8")
    .split("\n")
    .map((line) => line.match(/^([A-Z_0-9]+)="?([^"\r\n]*)"?/))
    .filter(Boolean)
    .map((m) => [m[1], m[2]]),
);

const KEY = env.YANDEX_API_KEY;
const FOLDER = env.YANDEX_FOLDER_ID;

