/**
 * Запускается один раз при старте сервера, до первого запроса.
 *
 * Нужен, чтобы поднять слушателя телеграма: вебхук у нас не работает —
 * защита Timeweb отбрасывает соединения с серверов телеграма, — поэтому за
 * сообщениями ходим сами.
 */
export async function register() {
  // Во время сборки этот файл тоже выполняется, но там ни базы, ни сети нет.
  if (process.env.NEXT_RUNTIME !== "nodejs") return;

  // Слушатель должен быть ровно один. Если контейнеров станет больше одного,
  // телеграм начнёт отвечать на getUpdates ошибкой 409 — тогда переменную
  // выставляем только одному из них.
  if (process.env.TELEGRAM_POLLING !== "1") return;

  const { startPolling } = await import("@/lib/telegram/polling");

  // Намеренно не ждём: цикл живёт столько же, сколько процесс, и если его
  // дождаться, сервер не начнёт принимать запросы.
  void startPolling().catch((error) => {
    console.error("telegram: слушатель не запустился", error);
  });
}
