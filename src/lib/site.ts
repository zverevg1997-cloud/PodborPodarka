// Канонический адрес сайта. Домен кириллический, а в коде он нужен в punycode:
// дарибот.рф → xn--80achr5ajr.xn--p1ai.
//
// Адрес без www. Раньше здесь стоял www — считалось, что апекс отдаёт на него
// редирект, но это осталось со времён Vercel: в Timeweb оба имени привязаны к
// приложению напрямую и отвечают одинаково. В Вебмастере площадка заведена
// как дарибот.рф, и хосты в карте сайта должны совпадать с ней, иначе Яндекс
// считает адреса чужими и не берёт ни одного.
export const SITE_URL =
  process.env.NEXT_PUBLIC_SITE_URL ?? "https://xn--80achr5ajr.xn--p1ai";

/**
 * Базовый адрес для ссылок, уходящих наружу: письма, редиректы после
 * подтверждения. На проде всегда канонический домен — за прокси Vercel
 * из самого запроса можно получить служебный адрес деплоя.
 */
export function resolveBaseUrl(requestUrl: string): string {
  return process.env.NODE_ENV === "production"
    ? SITE_URL
    : new URL(requestUrl).origin;
}

