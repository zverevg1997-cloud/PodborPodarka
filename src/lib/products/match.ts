/**
 * Подбор товаров из партнёрских выгрузок под идею из подборки.
 *
 * Правило одно и оно строгое: **все** слова заданной фразы должны найтись в
 * названии товара, и цена должна попасть в вилку идеи.
 *
 * Строгость не от перестраховки. При мягком поиске каталог отвечает на
 * «настольную игру» настольной лампой, на «мешок для сменной обуви» —
 * сменным ремешком, а на «железную дорогу» — сертификатом в музей железных
 * дорог. Всё это настоящие совпадения по общему слову, и все три никуда не
 * годятся: читатель видит под идеей не то, что обещано.
 *
 * Ищем при каждой отрисовке страницы, без кэша. Кэш тут и не включить:
 * корневой макет читает куки ради имени в шапке, из-за чего все страницы
 * сайта динамические. Но запрос дешёвый — отбор идёт по индексу цены, — так
 * что городить обходной путь не из-за чего.
 *
 * Поэтому фразу для поиска задаёт человек, отдельным полем у идеи, и только
 * там, где в каталоге действительно что-то есть. Где фразы нет — страница
 * по-прежнему ведёт на поиск Яндекс Маркета.
 */

import { prisma } from "@/lib/prisma";
import type { Product } from "@prisma/client";

/** Сколько карточек показываем под одной идеей. */
const LIMIT = 3;

/**
 * Слова, которые сами по себе ничего не значат.
 *
 * Запрос «подарочный сертификат» подходит ко всем семи тысячам впечатлений
 * БоксДари, и под идеей «сертификат в книжный магазин» оказывалась комната
 * ярости. А «подарочный сертификат спа» находит спа-программу и ничего
 * кроме — потому что в нём есть слово по делу.
 *
 * Отсюда правило: хотя бы одно слово запроса должно быть не из этого
 * списка. Считать совпадения и отсекать по их числу было бы хуже — порог
 * пришлось бы двигать каждый раз, когда каталог подрастёт.
 */
const GENERIC = new Set([
  "подарочн", "сертификат", "набор", "детск", "хорош", "больш",
  "нов", "красив", "удобн", "прост", "качествен", "лучш", "подарок",
]);

/**
 * Русские слова склоняются, а названия в выгрузках пишут как придётся.
 * Отрезаем окончание — этого хватает, чтобы «кружка» нашла «кружки».
 * Настоящая лемматизация тут была бы стрельбой из пушки.
 */
function stem(word: string): string {
  return word.replace(
    /(ами|ями|ов|ей|ам|ям|ах|ях|ой|ую|ые|ый|ий|ая|ое|ым|им|ом|ем|ы|и|а|я|у|ю|е)$/u,
    "",
  );
}

function words(text: string): string[] {
  return text
    .toLowerCase()
    // Цифры выбрасываем: «450 мл» из запроса в названии товара пишут как
    // придётся или не пишут вовсе, а требовать их — терять верные находки.
    .replace(/[^а-яёa-z\s]/gi, " ")
    .split(/\s+/)
    // Три буквы, а не четыре: иначе «спа» выпадало из сравнения, и запрос
    // про спа-сертификат находил что угодно.
    .filter((word) => word.length >= 3)
    .map(stem);
}

export async function findProducts(
  query: string,
  priceFrom: number,
  priceTo: number,
): Promise<Product[]> {
  const needed = words(query);
  if (needed.length === 0) return [];

  // Запрос из одних служебных слов не ищем вовсе: он подойдёт к чему угодно.
  // Сравниваем по началу слова, а не на равенство.
  //
  // Обрезка окончаний грубая и не ловит всего: «подарочный» она оставляла
  // как есть, в списке стояло «подарочн», и проверка молча не срабатывала.
  // Под «сертификат в книжный магазин» подставлялась комната ярости.
  if (needed.every((word) => [...GENERIC].some((g) => word.startsWith(g)))) {
    return [];
  }

  // Отбираем по цене и по первому слову в базе, остальное досеиваем здесь:
  // сравнивать основы слов средствами Postgres пришлось бы через отдельный
  // словарь, а товаров в вилке всегда немного.
  //
  // Предел широкий, и это не запас на будущее. Досев строгий — все слова
  // запроса должны найтись в названии, — и берём мы отсюда самое дешёвое.
  // Пока каталог был на тридцать тысяч, двухсот хватало с избытком. С
  // каталогом маркетплейсов первое слово запроса встречается у тысяч
  // товаров, и среди двухсот самых дешёвых из них может не оказаться ни
  // одного подходящего. Выглядело бы это так, будто товар просто исчез.
  const candidates = await prisma.product.findMany({
    where: {
      available: true,
      price: { gte: priceFrom, lte: priceTo },
      name: { contains: needed[0], mode: "insensitive" },
    },
    orderBy: { price: "asc" },
    take: 1000,
  });

  const seen = new Set<string>();
  const matched: Product[] = [];

  for (const product of candidates) {
    const name = words(product.name).join(" ");
    if (!needed.every((word) => name.includes(word))) continue;

    // Один товар в пяти цветах — это одна идея, а не пять. Схлопываем по
    // названию: в выгрузках варианты называются одинаково.
    const key = product.name.toLowerCase();
    if (seen.has(key)) continue;
    seen.add(key);

    matched.push(product);
    if (matched.length === LIMIT) break;
  }

  return matched;
}
