/**
 * Страницы-подборки под поисковые запросы вида «что подарить мальчику
 * 10 лет на день рождения».
 *
 * Идеи заданы заранее, а не генерируются при открытии страницы: она должна
 * открываться мгновенно и показывать поисковому роботу и человеку одно и то
 * же. Подбор под конкретного получателя живёт в анкете, ссылка на неё стоит
 * на каждой странице.
 *
 * Важно: страницы должны отличаться не только числом в заголовке. Подарки
 * трёхлетке и подростку не пересекаются, и если это перестанет быть так,
 * поисковик сочтёт раздел штамповкой и понизит сайт целиком.
 */

export interface GuideIdea {
  name: string;
  /** Почему подойдёт. Этого нет в чужих списках, ради этого и остаются. */
  reason: string;
  /** Ориентировочная вилка, рублей. Точные цены показывает сам Маркет. */
  priceFrom: number;
  priceTo: number;
  /** Запрос, с которым уходим на Маркет. */
  searchQuery: string;
}

export interface GiftGuide {
  slug: string;
  /**
   * Заголовок и h1 — дословно так, как люди ищут, включая порядок слов.
   * «Что подарить мальчику на 10 лет» набирает 10 684, а «мальчику 10 лет
   * на день рождения» — вдвое меньше. Поэтому начинаем с сильной формы, а
   * слабую дописываем во второй половине: страница совпадает с обеими.
   */
  title: string;
  description: string;
  /** Вводный абзац: чем этот возраст отличается от соседних. */
  intro: string;
  gender: "мальчик" | "девочка";
  age: number;
  /** На что смотреть при выборе — короткие оговорки от себя. */
  notes: string[];
  ideas: GuideIdea[];
  /** До 1500 рублей: эти варианты ищут отдельным запросом. */
  budgetIdeas: GuideIdea[];
}

