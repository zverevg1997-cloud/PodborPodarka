-- Закрываем служебную таблицу Prisma от публичного REST API Supabase.
--
-- _prisma_migrations создаёт сама Prisma, поэтому под правило о правах по
-- умолчанию из предыдущей миграции она не попала — та действует только на
-- таблицы, созданные после неё. В результате по публикуемому ключу читалась
-- вся история изменений схемы: названия миграций, даты, контрольные суммы.
--
-- Персональных данных там нет, но названия миграций рассказывают постороннему
-- о внутреннем устройстве базы больше, чем ему следует знать.
--
-- На миграции это не влияет: Prisma подключается владельцем таблицы, а
-- владелец политики RLS обходит.

ALTER TABLE "_prisma_migrations" ENABLE ROW LEVEL SECURITY;

REVOKE ALL ON "_prisma_migrations" FROM anon, authenticated;
